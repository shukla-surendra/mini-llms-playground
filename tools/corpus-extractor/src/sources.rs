//! The dataset registry — a manually-synced Rust mirror of
//! `custom-gpt-153m/src/gpt/data/sources.py`'s `DATASETS`. That Python file stays the
//! single source of truth for `docs/DATASETS.md` generation; this list exists so
//! `build-corpus` can download/parse the same sources without a Python dependency at
//! run time. Keep the two in sync by hand when a dataset is added, removed, or
//! reclassified — there is no shared source both sides derive from.

/// Which row-parsing branch a source's raw parquet schema needs — mirrors
/// `sources.py`'s `schema` field exactly (`"conversation"` / `"instruction"` /
/// `"oasst_tree"`), see `parquet_rows.rs` for what each branch actually does.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Schema {
    Conversation,
    Instruction,
    OasstTree,
}

#[derive(Debug, Clone, Copy)]
pub struct DatasetSource {
    pub hf_id: &'static str,
    pub name: &'static str,
    pub gated: bool,
    pub schema: Schema,
    pub summary: &'static str,
}

impl DatasetSource {
    /// Local directory name under `<data-dir>/raw/` — `hf_id` with `/` and `:`
    /// replaced by `__`, matching `sources.py`'s `DatasetSource.slug`.
    pub fn slug(&self) -> String {
        self.hf_id.replace('/', "__").replace(':', "__")
    }
}

