PUBLIC_DATASETS = tuple(d for d in DATASETS if not d.gated)
GATED_DATASETS = tuple(d for d in DATASETS if d.gated)


def by_id(hf_id):
    for source in DATASETS:
        if source.hf_id == hf_id:
            return source
    raise KeyError(f"Unknown dataset id: {hf_id}")


def selected(include_gated=True):
    return DATASETS if include_gated else PUBLIC_DATASETS
