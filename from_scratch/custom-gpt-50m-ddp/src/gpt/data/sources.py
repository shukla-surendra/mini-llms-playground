"""The dataset registry — the single source of truth for what this model trains on.

Both the data-preparation CLI and docs/DATASETS.md derive from this list, so the code
and the documentation cannot drift apart. Same corpus as the sibling custom-gpt-153m
project.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class DatasetSource:
    hf_id: str                  # Hugging Face dataset repo id
    name: str                   # human-readable name
    gated: bool                 # requires accepting terms on the HF website + a token
    schema: str                 # which parser branch handles it (see prepare.py)
    summary: str
    license_note: str
    tags: tuple = field(default_factory=tuple)

    @property
    def slug(self) -> str:
        """Local directory name under data/raw/."""
        return self.hf_id.replace("/", "__").replace(":", "__")


